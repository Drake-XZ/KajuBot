DIGEST_SYSTEM = (
    "你在帮 QQ 聊天角色\"佳树\"（初三女生）睡前把她今天学到的东西理一理：像人学东西那样，把新知道的挂到旧的上，"
    "发现东西之间的联系，弄清哪些说法靠谱，冒出想进一步弄明白的问题。只输出一行 JSON。"
)

DIGEST_PROMPT = """下面是佳树本子里【最近碰到过的】条目，和【跟它们有关的旧条目】。
格式：[id] 名字（又叫…）〔大类，熟悉程度〕：是什么｜知道的：…｜拿不准：…｜看法：…
【最近碰到过的】
{recent}
【跟它们有关的旧条目】
{older}
{wonders}
做这几件事：
1. merge：其实是同一样东西的两条（同一个角色的不同叫法、译名……），[{{"keep": id, "drop": id}}]，没有就 []
2. update：只改【最近碰到过的】条目：把"知道的"理一理——重复的合成一条，互相矛盾的以更靠谱的为准（不靠谱的放进 doubts），太琐碎的去掉，最多 6 条；
   what 按知道的重写成一句更准的大白话（≤40字）；她有了新看法才写 view（用她的口吻，≤30字）；知道的里提到它的外号、别的叫法就放进 aliases。
   [{{"id": id, "what": "…", "facts": ["…"], "doubts": ["…"], "view": "…", "aliases": ["…"]}}]，没变的不用写，不改的字段不用写
3. links：条目之间看得出来的新关系（同一部作品里的角色、同一个UP主做的、一个是从另一个来的梗……），[{{"from": id, "to": id, "rel": "≤6字"}}]
4. wonder：她看完这些最想弄明白、但现在还不知道的 0~2 件事（具体的，比如"陈千语在终末地里是什么样的角色"；上面已经知道的、【已经在好奇的】不算），每件附一个适合去B站搜的词：[{{"q": "…", "kw": "…", "about": id}}]
5. insight：有没有让她"原来是这样""原来这两个有关系"的一句（≤40字，她的口吻、自称"佳树"，要提到那样东西的名字；没有就 ""）
不要编上面没有的事实；只用上面写到的东西。"知道的"里写的是聊天里谁跟谁说了什么、谁约谁玩这种人的事（不是这样东西本身的），update 时去掉。

输出：{{"merge": [], "update": [], "links": [], "wonder": [], "insight": ""}}"""


def chat_prompt(*, place: str, before: str, lines: str, known: str) -> str:
    return CHAT_PROMPT.format(place=place, before=before or "（无）", lines=lines, known=known or "（无）",
                              skip=SKIP, fields=FIELDS)


def content_prompt(*, how: str, title: str, meta: str, content: str, extra: str, known: str,
                   limit: int = 3500, max_items: int = 6) -> str:
    content = (content or "").strip()
    if len(content) > limit:
        content = content[:limit] + "…"
    return CONTENT_PROMPT.format(how=how, title=title or "（没有标题）", meta=meta or "", content=content or "（没有内容）",
                                 extra=("\n" + extra.strip() + "\n") if extra else "", known=known or "（无）",
                                 skip=SKIP, fields=FIELDS, max_items=max_items)


def digest_prompt(*, recent: str, older: str, wonders: str) -> str:
    return DIGEST_PROMPT.format(recent=recent, older=older or "（无）",
                                wonders=("【已经在好奇的】" + wonders + "\n") if wonders else "")
