async def run(snap: dict, rec: dict, folder: str, tz, timeout: float, log=None, plan: str | None = None, ask=None) -> dict:
    """plan / ask 给离线对比用（voice_train\\scripts\\compare_plans.py）：换一版提示词、固定一个模型；线上不传。"""
    from kaju_core.senses import omni
    row = {"t": rec.get("t"), "kind": rec.get("kind"), "title": rec.get("title"), "said": rec.get("said"),
           "draft": rec.get("draft"), "final": rec.get("final"), "outcome": rec.get("outcome")}
    t0 = time.time()
    try:
        out, n = await (ask or omni.text)(plan or PLAN, user_prompt(snap), timeout=timeout)
        row.update(plan=parse(out), raw=None if parse(out) else (out or "")[:500], key=n)
    except Exception as e:  # noqa: BLE001
        row.update(plan=None, error=f"{type(e).__name__}: {e}"[:200])
    row["ms"] = int((time.time() - t0) * 1000)
    try:
        os.makedirs(folder, exist_ok=True)
        day = dt.datetime.fromtimestamp(float(row["t"] or time.time()), tz).strftime("%Y-%m-%d")
        with open(os.path.join(folder, day + ".jsonl"), "a", encoding="utf-8") as f:
            f.write(json.dumps(row, ensure_ascii=False) + "\n")
    except Exception as e:  # noqa: BLE001
        if log:
            log(f"影子规划器存不上 {type(e).__name__}: {e}")
    return row


def spawn(snap: dict, rec: dict, folder: str, tz, timeout: float, log=None) -> None:
    """在后台跑一次（没有事件循环就不跑）；任务的引用留着，免得被回收。"""
    try:
        loop = asyncio.get_running_loop()
    except RuntimeError:
        return
    task = loop.create_task(run(snap, rec, folder, tz, timeout, log))
    _TASKS.add(task)
    task.add_done_callback(_TASKS.discard)
