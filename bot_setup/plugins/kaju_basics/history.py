def face_text(face_id) -> str:
    try:
        name = FACE_NAMES.get(int(face_id))
    except (TypeError, ValueError):
        name = None
    return f"[表情：{name}]" if name else "[QQ表情]"


def move_into_place(ids: list, recs: list, arrived: dict, rid) -> int:
    """把记录 rid 往前挪到比它晚到的记录前面（ids/recs 原地改）。返回挪了几格。

    arrived：记录 id → 消息到达时间；没登记的记录当作不比任何人晚（不跨过去）。
    """
    if rid not in arrived or len(ids) != len(recs):
        return 0
    try:
        i = ids.index(rid)
    except ValueError:
        return 0
    t = arrived[rid]
    j = i
    while j > 0 and arrived.get(ids[j - 1], float("-inf")) > t:
        j -= 1
    if j == i:
        return 0
    ids.insert(j, ids.pop(i))
    recs.insert(j, recs.pop(i))
    return i - j


